"""Generates Aion's launcher icons, wordmarks and splash logo into app/src/forkRelease/res.

Run: python3 aion-tools/brand/make_brand.py
"""
import os
import re

from PIL import Image, ImageChops, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "app", "src", "forkRelease", "res")
BOLD = "/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf"
REGULAR = "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf"
MASTER = 1728  # 108 dp viewport * 16
BACKGROUND = (0x0F, 0x12, 0x26, 255)
VIOLET = (0x7C, 0x4D, 0xFF)
CYAN = (0x00, 0xD4, 0xFF)


def gradient(size):
    """Diagonal violet -> cyan gradient."""
    horizontal = Image.linear_gradient("L").rotate(45, expand=True).resize((size, size))
    return Image.composite(Image.new("RGB", (size, size), CYAN), Image.new("RGB", (size, size), VIOLET), horizontal)


def mark(size, monochrome=False):
    """The Aion mark on a 108-unit canvas: a gradient orb with a bold 'A' and a small star."""
    s = MASTER
    k = s / 108
    orb = Image.new("L", (s, s), 0)
    ImageDraw.Draw(orb).ellipse([24 * k, 24 * k, 84 * k, 84 * k], fill=255)
    glyph = Image.new("L", (s, s), 0)
    d = ImageDraw.Draw(glyph)
    w = int(7.5 * k)
    pts = [(39 * k, 73 * k), (54 * k, 35 * k), (69 * k, 73 * k)]
    d.line(pts, fill=255, width=w, joint="curve")
    for x, y in pts:
        d.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=255)
    d.line([(45.5 * k, 61 * k), (62.5 * k, 61 * k)], fill=255, width=int(5.5 * k))
    star = [(69 * k, 31 * k), (70.6 * k, 35.4 * k), (75 * k, 37 * k), (70.6 * k, 38.6 * k),
            (69 * k, 43 * k), (67.4 * k, 38.6 * k), (63 * k, 37 * k), (67.4 * k, 35.4 * k)]
    d.polygon(star, fill=255)
    out = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    if monochrome:
        out.putalpha(ImageChops.subtract(orb, glyph))
        out = Image.composite(Image.new("RGBA", (s, s), (255, 255, 255, 255)), out, out.getchannel("A"))
    else:
        colored = gradient(s).convert("RGBA")
        colored.putalpha(orb)
        out.alpha_composite(colored)
        white = Image.new("RGBA", (s, s), (255, 255, 255, 255))
        white.putalpha(ImageChops.multiply(glyph, orb))
        out.alpha_composite(white)
    return out.resize((size, size), Image.LANCZOS)


def cropped_mark(size):
    """Just the orb, edge to edge."""
    big = mark(int(size * 108 / 60))
    c = (big.width - size) // 2
    return big.crop((c, c, c + size, c + size))


def legacy_icon(size):
    s = size * 4
    base = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    ImageDraw.Draw(base).rounded_rectangle([0, 0, s - 1, s - 1], radius=int(s * 0.22), fill=BACKGROUND)
    big = mark(int(s * 108 / 80))
    c = (big.width - s) // 2
    base.alpha_composite(big.crop((c, c, c + s, c + s)))
    return base.resize((size, size), Image.LANCZOS)


def wordmark(width, height, color, with_logo):
    s = 4
    img = Image.new("RGBA", (width * s, height * s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    x = 0
    h = height * s
    if with_logo:
        img.alpha_composite(cropped_mark(h), (0, 0))
        x = int(h * 1.18)
    size = int(h * 0.74)
    while True:
        bold = ImageFont.truetype(BOLD, size)
        regular = ImageFont.truetype(REGULAR, size)
        total = d.textlength("Aion ", font=bold) + d.textlength("Browser", font=regular)
        if x + total <= width * s * 0.98 or size < 8:
            break
        size -= 4
    d.text((x, h // 2), "Aion", font=bold, fill=color, anchor="lm")
    x += int(d.textlength("Aion ", font=bold))
    d.text((x, h // 2), "Browser", font=regular, fill=color, anchor="lm")
    return img.resize((width, height), Image.LANCZOS)


def write_bitmap_xml(path, drawable):
    with open(path, "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Aion logo, generated by aion-tools/brand/make_brand.py -->\n'
                '<bitmap xmlns:android="http://schemas.android.com/apk/res/android"\n'
                f'    android:src="@drawable/{drawable}"\n    android:gravity="fill" />\n')


def main():
    for density, size in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        icon = legacy_icon(size)
        for name in ("ic_launcher", "ic_launcher_round", "ic_launcher_private", "ic_launcher_private_round"):
            icon.save(f"{RES}/mipmap-{density}/{name}.png")

    mark(432).save(f"{RES}/drawable-nodpi/ic_aion_foreground.png")
    mark(432, monochrome=True).save(f"{RES}/drawable-nodpi/ic_aion_monochrome.png")
    write_bitmap_xml(f"{RES}/drawable/ic_launcher_foreground.xml", "ic_aion_foreground")
    write_bitmap_xml(f"{RES}/drawable-v24/ic_launcher_foreground.xml", "ic_aion_foreground")
    write_bitmap_xml(f"{RES}/drawable/ic_launcher_monochrome.xml", "ic_aion_monochrome")
    write_bitmap_xml(f"{RES}/drawable/ic_splash_logo.xml", "ic_aion_foreground")

    colors = f"{RES}/values/colors.xml"
    text = open(colors).read()
    text = re.sub(r'<color name="ic_launcher_background">[^<]*</color>',
                  '<color name="ic_launcher_background">#0F1226</color>', text)
    open(colors, "w").write(text)

    logo = Image.new("RGBA", (347, 320), (0, 0, 0, 0))
    logo.alpha_composite(cropped_mark(300), (23, 10))
    logo.save(f"{RES}/drawable-nodpi/ic_wordmark_logo.png")

    dark = (0x20, 0x12, 0x3A, 255)
    white = (255, 255, 255, 255)
    wordmark(1327, 134, dark, False).save(f"{RES}/drawable-nodpi/ic_wordmark_text_normal.png")
    wordmark(1327, 134, white, False).save(f"{RES}/drawable-nodpi/ic_wordmark_text_private.png")
    for density, (w, h) in {"mdpi": (434, 80), "hdpi": (651, 120), "xhdpi": (868, 160),
                            "xxhdpi": (1302, 240), "xxxhdpi": (1736, 320)}.items():
        wordmark(w, h, dark, True).save(f"{RES}/drawable-{density}/ic_logo_wordmark_normal.png")
        wordmark(w, h, white, True).save(f"{RES}/drawable-{density}/ic_logo_wordmark_private.png")

    widget = Image.open(f"{RES}/drawable-hdpi/fenix_search_widget.png").convert("RGBA")
    ImageDraw.Draw(widget).rectangle([40, 35, 195, 200], fill=(255, 255, 255, 255))
    widget.alpha_composite(cropped_mark(146), (44, 43))
    widget.save(f"{RES}/drawable-hdpi/fenix_search_widget.png")
    print("done")


if __name__ == "__main__":
    main()
